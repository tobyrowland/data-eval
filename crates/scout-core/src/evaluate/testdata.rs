//! Fake ticket-tracker data built from the ticket keys the owner's own
//! data mentions, so they can see how linked work completes before they
//! have a real export. Every row is marked as test data, and the app warns
//! wherever it is used.

use super::links::TicketMention;
use std::hash::{Hash, Hasher};

/// The column that marks a row as Working Minds test data.
pub const TEST_COLUMN: &str = "Working Minds test data";

fn seed(key: &str) -> u64 {
    let mut h = std::collections::hash_map::DefaultHasher::new();
    ("wm-test-jira", key).hash(&mut h);
    h.finish()
}

fn date(t: i64) -> String {
    let (y, m, d) = crate::analyze::slack::civil_from_days(t.div_euclid(86_400));
    let secs = t.rem_euclid(86_400);
    format!(
        "{y:04}-{m:02}-{d:02} {:02}:{:02}",
        secs / 3600,
        secs % 3600 / 60
    )
}

fn csv_field(s: &str) -> String {
    if s.contains([',', '"', '\n']) {
        format!("\"{}\"", s.replace('"', "\"\""))
    } else {
        s.to_string()
    }
}

fn system_list(systems: &[&str]) -> String {
    let names: Vec<String> = systems
        .iter()
        .map(|s| super::links::system_name(s))
        .collect();
    names.join(", ")
}

/// A Jira-style CSV export with one fake ticket per key mentioned: about
/// three in four resolved shortly after their last mention, the rest still
/// open. Deterministic: the same mentions give the same file.
pub fn test_jira_csv(mentions: &[TicketMention]) -> String {
    let mut out =
        format!("Summary,Issue key,Issue Type,Status,Created,Resolved,Description,{TEST_COLUMN}\n");
    for m in mentions {
        let s = seed(&m.key);
        let kind = ["Bug", "Story", "Task"][(s % 3) as usize];
        let done = s % 100 < 75;
        let first = m.first.or(m.last);
        let last = m.last.or(m.first);
        let created = first.map(|t| t - ((s >> 8) % (3 * 86_400)) as i64);
        let resolved = last
            .filter(|_| done)
            .map(|t| t + 86_400 + ((s >> 24) % (13 * 86_400)) as i64);
        let status = if done {
            "Done"
        } else if s.is_multiple_of(2) {
            "In Progress"
        } else {
            "To Do"
        };
        let summary = format!(
            "Test ticket {} (mentioned {} time{} in {})",
            m.key,
            m.mentions,
            if m.mentions == 1 { "" } else { "s" },
            if m.systems.is_empty() {
                "your data".to_string()
            } else {
                system_list(&m.systems)
            }
        );
        let row = [
            csv_field(&summary),
            m.key.clone(),
            kind.to_string(),
            status.to_string(),
            created.map(date).unwrap_or_default(),
            resolved.map(date).unwrap_or_default(),
            "Fake ticket generated by Working Minds for testing. Not real data.".to_string(),
            "yes".to_string(),
        ];
        out.push_str(&row.join(","));
        out.push('\n');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn mention(key: &str) -> TicketMention {
        TicketMention::for_test(
            key,
            3,
            Some(1_614_679_200),
            Some(1_614_765_600),
            vec!["slack", "bitbucket"],
        )
    }

    #[test]
    fn deterministic_flagged_and_resolved_after_created() {
        let ms: Vec<TicketMention> = (1..=40).map(|i| mention(&format!("CRQ-{i}"))).collect();
        let a = test_jira_csv(&ms);
        assert_eq!(a, test_jira_csv(&ms));
        let rows = crate::analyze::tabular::parse_csv(&a);
        assert_eq!(rows[0][1], "Issue key");
        assert_eq!(rows.len(), 41);
        let done = rows[1..].iter().filter(|r| r[3] == "Done").count();
        assert!((20..=38).contains(&done), "{done}");
        for r in &rows[1..] {
            assert_eq!(r[7], "yes");
            assert!(r[0].contains("Slack, Bitbucket"), "{}", r[0]);
            if r[3] == "Done" {
                assert!(r[5] > r[4], "{r:?}");
            } else {
                assert!(r[5].is_empty());
            }
        }
    }
}
